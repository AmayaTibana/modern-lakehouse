USE WAREHOUSE LAKEHOUSE_WH;
USE DATABASE LAKEHOUSE;
USE SCHEMA STAGING;

TRUNCATE TABLE STG_POKEMON;
COPY INTO STG_POKEMON
  FROM @CURATED_STAGE/pokeapi/pokemon/
