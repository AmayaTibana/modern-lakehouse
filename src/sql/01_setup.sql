-- One-time Snowflake setup. Run manually in a worksheet as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS LAKEHOUSE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS LAKEHOUSE;
CREATE SCHEMA IF NOT EXISTS LAKEHOUSE.STAGING;
CREATE SCHEMA IF NOT EXISTS LAKEHOUSE.ANALYTICS;

USE WAREHOUSE LAKEHOUSE_WH;
CREATE FILE FORMAT IF NOT EXISTS LAKEHOUSE.STAGING.PARQUET_FF TYPE = PARQUET;

-- S3 access. Before running this, create the IAM role "snowflake-s3-role" in AWS
-- (read-only access to s3://lakehouse-amaya/curated/). After creating the integration,
-- run DESC INTEGRATION and copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID
-- into the role's trust policy in the AWS console (manual step, not stored here).
CREATE STORAGE INTEGRATION IF NOT EXISTS S3_LAKEHOUSE_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<AWS_ACCOUNT_ID>:role/snowflake-s3-role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://lakehouse-amaya/curated/');

DESC INTEGRATION S3_LAKEHOUSE_INT;

CREATE STAGE IF NOT EXISTS LAKEHOUSE.STAGING.CURATED_STAGE
  URL = 's3://lakehouse-amaya/curated/'
  STORAGE_INTEGRATION = S3_LAKEHOUSE_INT
  FILE_FORMAT = LAKEHOUSE.STAGING.PARQUET_FF;

LIST @LAKEHOUSE.STAGING.CURATED_STAGE;
EOF